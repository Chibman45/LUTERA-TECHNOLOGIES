create role anon nologin; create role authenticated nologin;
create schema auth; grant usage on schema auth to anon,authenticated;
create type auth.factor_type as enum('totp','phone','webauthn');
create type auth.factor_status as enum('verified','unverified');
create type auth.aal_level as enum('aal1','aal2');
create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
create table auth.mfa_factors(id uuid primary key,user_id uuid references auth.users(id),factor_type auth.factor_type,status auth.factor_status,secret text,created_at timestamptz not null,updated_at timestamptz not null);
create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id),factor_id uuid references auth.mfa_factors(id),aal auth.aal_level,created_at timestamptz,updated_at timestamptz,not_after timestamptz);
create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}'::jsonb)$$;
create function auth.uid() returns uuid language sql stable as $$select nullif(auth.jwt()->>'sub','')::uuid$$;
create schema storage;
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid default gen_random_uuid() primary key,bucket_id text references storage.buckets(id),name text);
alter table storage.objects enable row level security;
create function public.rls_auto_enable() returns event_trigger language plpgsql as $$begin return;end$$;
grant usage on schema storage to anon,authenticated;
grant select,insert,delete on storage.objects to anon,authenticated;
